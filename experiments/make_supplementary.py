#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""make_supplementary.py -- build the supplementary tables from the per-station CSVs.

The Supplementary Materials statement in the manuscript names four items.  Rather
than leave them as promises, this script generates the two tables that are
computable from the archived per-station outputs, so the statement matches what
actually exists.

  Table S1  per-station Gate 3 coefficients (all 14 data sets)
  Table S2  across-station sign agreement for the band coupling (D1/D2/D3)

Figures S1 and S2 are the two existing figures moved out of the main text
(per-station band scatter; storm case study).

Run on the cluster (needs pandas + the result directory).
"""
from __future__ import annotations

import glob
import os

import numpy as np
import pandas as pd

RES = "/data/ssd-stor/fsf/workspaces/research_ulf/ground_pc5/" \
      "v8_entropy_dissipation/results"
OUT = "/data/ssd-stor/fsf/workspaces/research_ulf/ground_pc5/" \
      "v8_entropy_dissipation/results/supplementary_tables.md"

# 2023-2024 come from the raw B015 archive: the processed Meridian product used
# for 2011-2022 stops at 2022, while the archive continues to 2024 (see the data
# source note under the multi-year table in the manuscript).
P1 = ([(y, "zw") for y in range(2011, 2023)]
      + [(2023, "zwraw"), (2024, "zwraw")])
P2 = [(y, "zw2") for y in (2025, 2026)]
METRICS = ["SampEn", "SE_full", "WPE", "CH_C", "Tsallis_q1.5", "IR_ordinal"]


def main():
    # ---------------- Table S1 ----------------
    lines = ["# Supplementary tables", "",
             "Generated by `v8_local/code/make_supplementary.py`. Every number is",
             "reproduced from the archived per-station result files; the window tag",
             "is pinned to w600 and the source and year are pinned per row.", "",
             "## Table S1. Per-station Gate 3 coefficients (all 16 data sets)",
             "", "Partial Spearman correlation between each measure and "
             "log P_Pc5 given log E_Pc5,",
             "with the Pedersen conductance modulated by AE. One row per station.", ""]
    n_rows = 0
    # each entry carries its own source tag, so the outer label is only cosmetic
    for _src, group, tag in (("mixed", P1, "Phase-I"), ("zw2", P2, "Phase-II")):
        for year, s_ in group:
            p = os.path.join(RES, "e2_sigma_%s%d.csv" % (s_, year))
            if not os.path.exists(p):
                continue
            d = pd.read_csv(p)
            d = d[(d.band == "Pc5") & (d.scheme == "AE") & (d.metric.isin(METRICS))]
            if d.empty:
                continue
            piv = d.pivot_table(index="station", columns="metric",
                                values="p_P_given_E", aggfunc="mean")
            piv = piv.reindex(columns=[m for m in METRICS if m in piv.columns])
            lines.append("### %s %d (%s, n=%d stations)"
                         % (tag, year, s_, len(piv)))
            lines.append("")
            hdr = "| station | " + " | ".join(piv.columns) + " |"
            sep = "|" + "---|" * (len(piv.columns) + 1)
            lines += [hdr, sep]
            for st, row in piv.iterrows():
                cells = ["%+.3f" % v if np.isfinite(v) else "n/a" for v in row]
                lines.append("| %s | %s |" % (st, " | ".join(cells)))
                n_rows += 1
            lines.append("")

    # ---------------- Table S2 ----------------
    p = os.path.join(RES, "station_consistency.csv")
    lines += ["## Table S2. Across-station sign agreement for the band coupling", "",
              "Number of stations sharing the majority sign of",
              "Spearman(metric, log E_band), for the three main data sets.", ""]
    if os.path.exists(p):
        d = pd.read_csv(p)
        cols = [c for c in d.columns if c not in ("metric", "band")]
        lines.append("| metric | band | " + " | ".join(cols) + " |")
        lines.append("|" + "---|" * (len(cols) + 2))
        for _, r in d.iterrows():
            cells = []
            for c in cols:
                v = r[c]
                try:
                    tup = eval(v) if isinstance(v, str) else v
                    cells.append("%+.3f (%d/%d)" % (tup[0], tup[1], tup[2]))
                except Exception:
                    cells.append(str(v))
            lines.append("| %s | %s | %s |" % (r["metric"], r["band"],
                                               " | ".join(cells)))
    else:
        lines.append("*`station_consistency.csv` not found — run "
                     "`station_consistency.py` first.*")

    lines += ["", "## Figures S1 and S2", "",
              "- **Figure S1.** Per-station entropy-energy scatter for all four bands "
              "(MHT, 2015): `mb_zw_MHT2015_bands.png`",
              "- **Figure S2.** Swarm Joule-heating case study of 17 March 2015: "
              "`case_2015_storm_WPE.png`", ""]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("[supp] wrote %s  (%d station rows in S1)" % (OUT, n_rows))


if __name__ == "__main__":
    main()
